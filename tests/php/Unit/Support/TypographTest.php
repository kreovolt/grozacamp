    #[DataProvider('cases')]
    public function test_rules(string $in, string $expected): void
    {
        $this->assertSame(self::typo($expected), Typograph::apply($in));
    }

    #[DataProvider('cases')]
    public function test_idempotent(string $in, string $expected): void
    {
        $once = Typograph::apply($in);
        $this->assertSame($once, Typograph::apply($once));
    }

    /** Меняются только пробелы (и тире между словами): вернув обычные пробелы, получаем исходный текст. */
    #[DataProvider('cases')]
    public function test_only_whitespace_changes(string $in, string $expected): void
    {
        $out = Typograph::apply($in);
        $plain = static fn (string $s): string => str_replace([' - ', ' – '], ' — ', (string) preg_replace('/[ \t\x{00A0}]+/u', ' ', $s));
        $this->assertSame($plain($in), $plain($out));
    }

    public function test_urls_and_emails_are_left_alone(): void
    {
        foreach (['https://vk.com/grozacamp', 'http://example.ru/a-b/10-20?x=в&y=1', 'mailto:a@b.ru', '2474347@bk.ru', 'ivan.petrov-8@mail.ru'] as $url) {
            $this->assertSame($url, Typograph::apply($url), $url);
            $this->assertSame([[$url, false]], Typograph::segments($url), $url . ': внутри адреса не ставим nobr');
        }
    }

    public function test_invalid_utf8_is_returned_as_is(): void
    {
        $bad = "\xff в лесу";
        $this->assertSame($bad, Typograph::apply($bad));
        $this->assertSame([[$bad, false]], Typograph::segments($bad));
    }

    public function test_apply_keeps_length_when_spaces_are_single(): void
    {
        foreach (self::cases() as [$in]) {
            if (preg_match('/[ \t]{2,}/', $in) === 1) {
                continue;
            }
            $this->assertSame(mb_strlen($in), mb_strlen(Typograph::apply($in)), $in);
        }
    }

